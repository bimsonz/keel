/**
 * Builds forge-lite's S-1 trees into `src/generated/forge-lite-trees.ts`: for
 * each of the eight changes, the `src` tree before it and after it, made from
 * the fixture by applying the real patches with `git apply`. Node and workerd
 * both import the module, so a contract can read real trees in either.
 */
import { execFileSync } from "node:child_process";
import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const fixture = join(root, "fixtures/forge-lite");
const scenario = (name: string) => join(fixture, "scenarios", name);
const rewritten = (name: string) =>
  fileURLToPath(new URL(`../forge-lite/${name}`, import.meta.url));

const A = scenario("s1/a.patch");
const B = scenario("s1/b.patch");
const B_REVISED = scenario("s1/b-revised.patch");

/** Each item: the patches that make its base from the fixture, then the one that makes its head. */
const ITEMS: Readonly<
  Record<string, { readonly base: readonly string[]; readonly change: string }>
> = {
  F01: { base: [], change: B },
  F02: { base: [A, B, B_REVISED], change: scenario("s2/careless.patch") },
  F03: { base: [A, B], change: B_REVISED },
  F04: { base: [], change: rewritten("F04.patch") },
  F05: { base: [], change: rewritten("F05.patch") },
  F06: { base: [A, B, B_REVISED], change: rewritten("F06.patch") },
  F07: { base: [], change: A },
  F08: { base: [], change: rewritten("F08.patch") },
};

const filesUnder = (dir: string, at = dir): string[] =>
  readdirSync(at, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? filesUnder(dir, join(at, entry.name))
      : [relative(dir, join(at, entry.name))],
  );

const contents: string[] = [];
const indexOf = (text: string): number => {
  const known = contents.indexOf(text);
  return known === -1 ? contents.push(text) - 1 : known;
};

/** The `src` tree after `patches`, as path → index into `contents`. Only `src/` is patched: the tests are not read. */
const treeAfter = (patches: readonly string[]): Record<string, number> => {
  const work = mkdtempSync(join(tmpdir(), "keel-forge-lite-"));
  try {
    cpSync(join(fixture, "src"), join(work, "src"), { recursive: true });
    for (const patch of patches)
      execFileSync("git", ["apply", "--include=src/*", patch], { cwd: work, stdio: "pipe" });
    return Object.fromEntries(
      filesUnder(work)
        .toSorted()
        .map((path) => [
          path.split("\\").join("/"),
          indexOf(readFileSync(join(work, path), "utf8")),
        ]),
    );
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
};

const trees = Object.fromEntries(
  Object.entries(ITEMS).map(([id, item]) => [
    id,
    { base: treeAfter(item.base), head: treeAfter([...item.base, item.change]) },
  ]),
);

const out = new URL("../src/generated/", import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(
  new URL("forge-lite-trees.ts", out),
  [
    "// Generated by packages/testing/scripts/gen.ts from fixtures/forge-lite. Never committed.",
    `export const CONTENTS: readonly string[] = ${JSON.stringify(contents)};`,
    `export const TREES: Readonly<Record<string, { readonly base: Readonly<Record<string, number>>; readonly head: Readonly<Record<string, number>> }>> = ${JSON.stringify(trees)};`,
    "",
  ].join("\n"),
);
